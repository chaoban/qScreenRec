path = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), 'i18n', 'qscreenrec_zh_TW.ts')
src = open(path, encoding='utf-8').read()
missing = []

def repl(m):
    source_xml = m.group(1)
    key = html.unescape(source_xml)
    zh = T.get(key)
    if zh is None:
        missing.append(key)
        return m.group(0)
    return m.group(0)[:m.start(2) - m.start(0)] + '<translation>' + html.escape(zh, quote=False) + '</translation>'

src = re.sub(r'<source>(.*?)</source>(?:(?!<source>).)*?(<translation[^>]*?(?:/>|>.*?</translation>))', repl, src, flags=re.S)
open(path, 'w', encoding='utf-8').write(src)
if missing:
    print('MISSING:', missing)
    sys.exit(1)
print('ok')
